// 系统图标唯一取用口（状态栏等"要系统默认图标"的场合）。
//
// 【为什么单独一层】"用系统默认图标"这条要求一旦散开就会烂：每个调用点各自
// ExtractIconEx / SHGetStockIconInfo，句柄归属各不相同 —— 必然有人漏 DestroyIcon，
// 也必然有人把大图标槽填进需要小图标的地方（发虚）。
// 本模块把"哪一枚语义图标对应哪个系统资源"收成一张表，句柄进程级缓存、归本模块
// 持有，调用方只读借用、不销毁。
//
// 【两条取数路径，可靠性不同】
//   1. SHGetStockIconInfo(SIID_*)  —— **文档化的稳定接口**，首选。
//   2. 系统 DLL 的序号资源（shell32/imageres 的第 N 号）—— **序号不是稳定 API**：
//      跨 Windows 版本与语言包会漂（实测：Windhawk Exbar.cpp 注释里的
//      "shell32,249 = 日期"在 Win11 上其实是**时钟**，不是日历）。
//      所以它只用在 SIID 没覆盖的形状上，且必须带兜底。
//
// 【降级链】SIID → 序号资源 → 调用方自己的字形兜底 → 空。
// 取不到就返回 nullptr，调用方**不画图标**，绝不画空白方块。
//
// 【为什么没有"日历/眼睛"】系统资源里确实没有日历位图（实测扫过 shell32 0..130
// 与 imageres 0..130），也没有眼形位图。这两类形状走 Segoe Fluent Icons 字形
// （见 icon_glyph.h）—— 那也是系统字体，只是位图形态。
#pragma once
#include "common.h"

namespace sysicon {

// 语义图标。只在这里列一次，其余地方按语义引用，不写死资源序号。
enum class Id {
    None = 0,
    Folder,    // 文件夹
    Document,  // 文档 / 文件
    Check,     // 对勾（已选）
    Size,      // 容量（带底座的立体文件夹 —— Windows 的"文件夹 + 度量"位图）
    Disk,      // 硬盘（卷空间）
};

// 取图标。进程级缓存，句柄归本模块持有到进程结束；调用方**只读借用，不要销毁**。
// 取不到返回 nullptr（调用方自行决定兜底）。
HICON Get(Id id);

// 主题切换时丢弃缓存（库存图标随系统主题变化，重取一次即可）。
// 句柄在丢弃时一并销毁 —— 本模块是这些句柄唯一的持有者。
void Invalidate();

}  // namespace sysicon
